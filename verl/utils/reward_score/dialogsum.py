import re


def extract_solution(solution_str, method="flexible"):
    assert method in ["strict", "flexible"]

    if method == "strict":
        # this also tests the formatting of the model
        solution = re.search("#### (\\-?[0-9\\.\\,]+)", solution_str)
        if solution is None:
            final_answer = None
        else:
            final_answer = solution.group(0)
            final_answer = final_answer.split("#### ")[1].replace(",", "").replace("$", "")
    elif method == "flexible":
        pattern = r"<answer>(.*?)</answer>"
        matches = re.findall(pattern, solution_str, re.DOTALL)
        return matches[-1] if matches else ""


def compute_edit_distance(s1: str, s2: str) -> int:
    """计算两个字符串的编辑距离"""
    if len(s1) < len(s2):
        return compute_edit_distance(s2, s1)

    if len(s2) == 0:
        return len(s1)

    previous_row = range(len(s2) + 1)
    for i, c1 in enumerate(s1):
        current_row = [i + 1]
        for j, c2 in enumerate(s2):
            insertions = previous_row[j + 1] + 1
            deletions = current_row[j] + 1
            substitutions = previous_row[j] + (c1 != c2)
            current_row.append(min(insertions, deletions, substitutions))
        previous_row = current_row

    return previous_row[-1]


def compute_score(solution_str, ground_truth, method="flexible", format_score=0.0, score=1.0):
    answer = extract_solution(solution_str=solution_str, method=method)
    if answer is None:
        return 0
    else:
        if answer == ground_truth:
            return score
        elif answer.replace(" ", "").lower() == ground_truth.replace(" ", "").lower():
            return 0.9
        else:
            processed_answer = answer.replace(" ", "").lower()
            processed_truth = ground_truth.replace(" ", "").lower()

            edit_dist = compute_edit_distance(processed_answer, processed_truth)
            max_len = max(len(processed_answer), len(processed_truth))
            if max_len == 0:
                return 0

            similarity = 1 - (edit_dist / max_len)
            # if similarity > 0.5:
            #     return similarity
            return similarity
